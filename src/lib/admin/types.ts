import type { Database, Json } from "@/lib/supabase/database.types";
type Tables = Database["public"]["Tables"];
export type Territory = Pick<Tables["territories"]["Row"], "id" | "kind" | "code" | "name" | "parent_id">;
export type Office = Pick<Tables["offices"]["Row"], "id" | "name" | "kind" | "territory_id" | "active"> & { territory_name: string };
export type RoleGrant = Tables["platform_role_grants"]["Row"];
export type Mandate = Tables["office_mandates"]["Row"] & { office_name: string; office_active: boolean };
export type AccessUser = { id: string; email: string; display_name: string };
export type UserAccess = { user: AccessUser | null; roles?: RoleGrant[]; mandates?: Mandate[] };
export type AuditEvent = { id: string; occurred_at: string; actor_name: string | null; actor_user_id: string | null; entity: string; entity_id: string; action: string; details: { before?: Record<string, Json>; after?: Record<string, Json> } };
export type AdminOverview = { territories: Territory[]; offices: Office[]; territory_count: number; office_count: number; audit: AuditEvent[] };
export type AdminFormState = { error?: string; errors?: Record<string, string> };
